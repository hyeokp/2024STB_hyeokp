# 예제 1. 수강생 A가 퀴즈 문제를 맞힐 확률을 50%라고 할 때, 총 4번의 시도 중에서 3번 정답을 맞출 확률은?
# 확률 함수
dbinom(3,4,0.5)
# 누적 함수
pbinom(3,4,0.5)
# 누적 함수의 값은 성공확률이 0.5인 시행에서 4번 중 3번 이하로 성공할 확률을 의미한다.


# 문제 1. A사에서 생산한 1,000개의 제품 중에서 10개가 불량품이라고 한다. 이를 기반으로 10개의 제품을 임의로 선정하여 불량품이 2개 미만이면 검사에 통과할 수 있다고 할 때 검사를 통과할 확률은?

# 먼저 검사를 통과할 확률을 알아보자. 불량품이 2개 미만이여야 하므로 불량품이 0개인 경우와 불량품이 1개인 경우가 통과할 수 있는 시나리오이다.

# 확률 함수 dbinom(성공 횟수, 시행 횟수, 성공 확률)을 사용하는 것이 적합하다.

# 각 제품이 불량일 확률은 10/1,000 이므로 0.01이다.

# 불량이 0개인 경우
dbinom(0,10,0.01)

# 불량이 1개인 경우
dbinom(1,10,0.01)

# 각각의 값인 0.9043821과 0.09135172을 더하면,
0.9043821 + 0.09135172

# 따라서, 검사를 통과할 확률은 0.9957338이다.




# 문제 2. 카페의 손님이 실제로 음료수를 주문하는 확률이 80%이다. 즉, 카페에 들어왔다가 그냥 나가는 확률이 20%가 된다. 이 때, 100명의 손님 중 91명 이상이 음료수를 주문할 확률을 계산해 보자.

# 이번 문제는 누적 함수를 활용하면 풀이가 쉽다. 다만 누적 함수는 어떠한 개수 이하의 확률을 반환하므로 1에서 90명이 주문할 확률을 빼면 된다.

pbinom(90,100,0.8)
1-0.9976664

# 따라서 100명의 손님 중 91명 이상이 음료수를 주문할 확률은 0.0023336이다.





